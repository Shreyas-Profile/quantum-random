"""FastAPI backend serving the quantum random bit stream.

Endpoints:
  GET  /api/status          — service metadata, bits available, last NIST run
  GET  /api/bits?n=256      — pull a batch of n fresh bits (max 65536)
  GET  /api/coin            — one quantum-random coin flip
  GET  /api/dice?sides=6    — one quantum-random die roll
  GET  /api/nist            — latest NIST SP 800-22 report (JSON)
  WS   /ws/stream           — live bit stream, pushes one bit per ~50ms

CORS is wide-open so the static frontend on quantum.shreyas.uk can
consume it from the browser.

The server reads bits from `data/clean.bits`, which is either
regenerated by the pipeline (capture → extractor) or by the synthetic
generator for testing. If the file runs low, the server pauses the
stream and the status endpoint reports the shortage honestly.
"""

from __future__ import annotations

import asyncio
import json
from contextlib import asynccontextmanager
from pathlib import Path

import numpy as np
from fastapi import FastAPI, WebSocket, WebSocketDisconnect
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse


CLEAN_BITS_PATH = Path("data/clean.bits")
NIST_REPORT_PATH = Path("data/nist.json")
STREAM_INTERVAL_MS = 50  # one bit roughly every 50ms on the websocket


class BitPool:
    """In-memory pool of certified-random bits backed by the clean.bits file."""

    def __init__(self, path: Path):
        self.path = path
        self.cursor = 0
        self._bits: np.ndarray = np.array([], dtype=np.uint8)
        self._lock = asyncio.Lock()
        self.reload()

    def reload(self) -> None:
        if self.path.exists():
            self._bits = np.unpackbits(np.frombuffer(self.path.read_bytes(), dtype=np.uint8))
        else:
            self._bits = np.array([], dtype=np.uint8)
        self.cursor = 0

    @property
    def total(self) -> int:
        return int(self._bits.size)

    @property
    def remaining(self) -> int:
        return max(0, self.total - self.cursor)

    async def take(self, n: int) -> np.ndarray:
        async with self._lock:
            if n > self.remaining:
                raise RuntimeError(f"Bit pool exhausted: need {n}, have {self.remaining}.")
            out = self._bits[self.cursor : self.cursor + n]
            self.cursor += n
            return out.copy()


pool = BitPool(CLEAN_BITS_PATH)


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Reload on startup in case the pipeline has produced fresh bits
    pool.reload()
    yield


app = FastAPI(
    title="quantum-random",
    description="Webcam-sourced quantum random bits, NIST-certified.",
    version="0.1.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)


@app.get("/api/status")
async def status():
    nist = None
    if NIST_REPORT_PATH.exists():
        nist = json.loads(NIST_REPORT_PATH.read_text())
    return {
        "service": "quantum-random",
        "bits_total": pool.total,
        "bits_remaining": pool.remaining,
        "source": "webcam LSB + Von Neumann + SHA-256",
        "nist_passed": nist["passed_count"] if nist else None,
        "nist_total": nist["total"] if nist else None,
        "nist_last_run": nist is not None,
    }


@app.get("/api/bits")
async def get_bits(n: int = 256):
    n = max(1, min(65536, n))
    if n > pool.remaining:
        return JSONResponse(
            {"error": "pool exhausted", "available": pool.remaining},
            status_code=503,
        )
    bits = await pool.take(n)
    return {
        "n": n,
        "bits": "".join(str(int(b)) for b in bits),
    }


@app.get("/api/coin")
async def coin():
    if pool.remaining < 1:
        return JSONResponse({"error": "pool exhausted"}, status_code=503)
    bit = (await pool.take(1))[0]
    return {"face": "heads" if int(bit) else "tails", "bit": int(bit)}


@app.get("/api/dice")
async def dice(sides: int = 6):
    sides = max(2, min(1000, sides))
    # Reject-sampling to avoid modulo bias: pick the smallest k with 2^k >= sides
    k = int(np.ceil(np.log2(sides)))
    if pool.remaining < k:
        return JSONResponse({"error": "pool exhausted"}, status_code=503)
    for _ in range(64):
        if pool.remaining < k:
            return JSONResponse({"error": "pool exhausted"}, status_code=503)
        bits = await pool.take(k)
        value = 0
        for b in bits:
            value = (value << 1) | int(b)
        if value < sides:
            return {"sides": sides, "roll": value + 1}
    return JSONResponse({"error": "could not sample"}, status_code=500)


@app.get("/api/nist")
async def nist_report():
    if not NIST_REPORT_PATH.exists():
        return JSONResponse({"error": "no NIST report yet"}, status_code=404)
    return json.loads(NIST_REPORT_PATH.read_text())


@app.websocket("/ws/stream")
async def stream(ws: WebSocket):
    await ws.accept()
    try:
        while True:
            if pool.remaining < 1:
                await ws.send_json({"error": "pool exhausted"})
                await asyncio.sleep(1)
                continue
            bit = int((await pool.take(1))[0])
            await ws.send_json({"bit": bit, "remaining": pool.remaining})
            await asyncio.sleep(STREAM_INTERVAL_MS / 1000)
    except WebSocketDisconnect:
        return


if __name__ == "__main__":
    import uvicorn

    uvicorn.run("quantum_random.server:app", host="0.0.0.0", port=8008, reload=False)
